"""
Agent 2: Web Research Agent
Executes web searches across DuckDuckGo, gathers verified sources,
deduplicates results, and surfaces grounded source records for the downstream analyst.
"""

import logging
from typing import Callable, Optional

from config import DEPTH_CONFIG
from models.schemas import ResearchPlan, SourceRecord
from tools.web_search import batch_search

logger = logging.getLogger(__name__)


def execute_web_research(
    plan: ResearchPlan,
    depth: str = "Standard",
    progress_callback: Optional[Callable[[str, int, int], None]] = None,
    ddgs_client: Optional[object] = None,
) -> tuple[list[SourceRecord], list[str]]:
    """
    Executes web research based on queries generated by the Research Planner.

    Args:
        plan: Validated ResearchPlan from Agent 1
        depth: Depth profile ("Quick", "Standard", "Detailed")
        progress_callback: Optional callback for UI progress updates (status_message, current, total)
        ddgs_client: Injected DDGS instance for testing/mocking

    Returns:
        (sources, failed_queries)
    """
    depth_settings = DEPTH_CONFIG.get(depth, DEPTH_CONFIG["Standard"])
    max_queries = depth_settings["max_queries"]
    max_results_per_query = depth_settings["max_results_per_query"]

    # Select queries up to the depth limit
    selected_queries = plan.search_queries[:max_queries]
    if not selected_queries:
        selected_queries = [plan.topic]

    total_queries = len(selected_queries)
    logger.info("Starting web research with %d queries (Depth: %s)", total_queries, depth)

    if progress_callback:
        progress_callback(f"Executing web searches across {total_queries} queries...", 0, total_queries)

    sources, failed_queries = batch_search(
        queries=selected_queries,
        max_results_per_query=max_results_per_query,
        max_total_sources=max_queries * max_results_per_query + 4,
        ddgs_client=ddgs_client,
    )

    if progress_callback:
        progress_callback(
            f"Collected {len(sources)} unique verified sources ({len(failed_queries)} failed)",
            total_queries,
            total_queries,
        )

    logger.info(
        "Web research complete: %d verified sources retrieved (%d queries failed)",
        len(sources),
        len(failed_queries),
    )

    return sources, failed_queries
